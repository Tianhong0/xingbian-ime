        /// <summary>排空本线程的消息队列。TSF / 窗口过程都需要它。</summary>
        public static int Pump()
        {
            int n = 0;
            MSG msg;
            while (PeekMessageW(out msg, IntPtr.Zero, 0, 0, PM_REMOVE))
            {
                TranslateMessage(ref msg);
                DispatchMessageW(ref msg);
                n++;
                if (n > 10000) break;
            }
            return n;
        }
